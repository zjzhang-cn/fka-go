// Package prompts 是**所有进模型的系统话术的唯一出处**。
//
// ## 为什么单独一个包
//
// 在这之前，问答提示写死在 llm，工具提示写死在 agent 循环，两边各写一份「不要
// Markdown」「列依据」。改一处就会漏另一处——还看不出来，因为两段文字长得像但
// 已经不一致了。收成一个包后：
//
//   - 公共规则只写一遍（noMarkdownRule 与 evidenceConstitution）；
//   - 所有进模型的话术只此一处，要读全貌不必翻遍调用方；
//   - 拼装规则也只写一遍（Compose），技能目录这类追加段落不会再出现「这条路径
//     空一行、那条路径没空」的差异。
//
// 纯文本 + 纯函数：不碰 IO。测试因此完全离线。
//
// （这里曾经手写过 `join` / `trimSpace` / `isSpace` 三个字符串工具——理由是「这个包
// 不碰 IO」，而 `strings` 不是 IO。三十行手写代码换来的只是把标准库重写一遍，
// 其中 `trimSpace` 还只认 ASCII 空白。）
//
// ## 它是默认值，不是硬编码
//
// 这套话术描述的是**证据纪律**，不是产品身份。想要完全不同人格的部署给一份
// 自己的提示词即可（`app.Options` → `RunnerOptions.SystemPrompt`）——所以
// 「这段文字过时了」的担心不成立：它只是默认值，而默认值该讲清楚自己在守什么。
package prompts

