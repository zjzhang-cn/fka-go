// Compose 系统提示 + 各来源追加的段落（技能目录就是它），空段跳过。
//
// 拼装只此一份：以前这一步散在 agent 循环里的三元表达式中，加第二条要拼装的路径
// 时又得复制一遍。sections 为空时原样返回 base，不留下尾随空行。
func Compose(base string, sections []string) string {
	extra := make([]string, 0, len(sections))
	for _, section := range sections {
		if trimmed := strings.TrimSpace(section); trimmed != "" {
			extra = append(extra, trimmed)
		}
	}
	if len(extra) == 0 {
		return base
	}
	return base + "\n\n" + strings.Join(extra, "\n")
}

// weekdays 中文星期。用固定表而不是 `time.Weekday.String()`：后者是英文，
// 而这套提示词全部是中文，混进一个英文单词会让人以为是别的段落。
var weekdays = [...]string{"星期日", "星期一", "星期二", "星期三", "星期四", "星期五", "星期六"}

// DateSection 当前日期，作为一段事实注入 system prompt。
//
// ## 为什么只到「日」，不含时分
//
// system 段每轮都会进入前缀缓存的比对：精确到分钟，缓存每分钟都失效；只到日，
// 一天才变一次。模型需要的是「今天是哪天」（回答「今天」「明天」「最近」），
// 不需要钟点。
//
// 时区用本机的（`now` 由调用方传入，本函数不读时钟，便于测试）：这是一个在用户
// 自己机器上跑的程序，「今天」指的是用户那边的今天。
func DateSection(now time.Time) string {
	return fmt.Sprintf("当前日期：%s（%s，时区 %s）。回答「今天」「明天」「最近」等与日期相关的问题时以此为准。",
		now.Format("2006-01-02"), weekdays[now.Weekday()], now.Format("MST"))
}

// joinConcat 拼宪法与该路径的追加段。宪法是共用的，所以拼装只此一处。
func joinConcat(base []string, extra ...string) string {
	lines := make([]string, 0, len(base)+len(extra))
	lines = append(lines, base...)
	lines = append(lines, extra...)
	return strings.Join(lines, "\n")
}
